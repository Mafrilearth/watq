import { ARCHETYPES, ARCHETYPE_METAS } from "../data";

export interface CollaborationManual {
  typeCode: string;
  archetypeTitle: string;
  callsign?: string;
  workingStyle: string;
  communicationStyle: string;
  howToGiveFeedback: string;
  cognitiveDrainers: string[];
  cognitiveBoosters: string[];
  meetingPreference: string;
  decisionMakingStyle: string;
  markdownContent: string;
}

/**
 * Generates an Enterprise Personal Collaboration Manual ("How to Work with Me")
 * Formatted for GitHub Profile READMEs, Notion Workspaces, and Team Onboarding.
 */
export function generateCollaborationManual(
  typeCode: string,
  callsign?: string,
): CollaborationManual {
  const code = typeCode.toUpperCase();
  const archetype = ARCHETYPES[code] || ARCHETYPES.INTJ;
  const meta = ARCHETYPE_METAS[code] || ARCHETYPE_METAS.INTJ;

  const isIntrovert = code.startsWith("I");
  const isIntuitive = code[1] === "N";
  const isThinking = code[2] === "T";
  const isJudging = code[3] === "J";

  const workingStyle = isJudging
    ? "Structured, methodical, milestone-driven with clear deliverables planned in advance."
    : "Adaptive, iterative, agile with emergent exploration and situational problem-solving.";

  const communicationStyle = isIntrovert
    ? "Asynchronous-first: I communicate best in structured written briefs, Slack/docs, and value time to reflect before speaking."
    : "Synchronous & verbal: I think out loud, value real-time brainstorms, and appreciate energetic collaborative momentum.";

  const howToGiveFeedback = isThinking
    ? "Direct, objective, and data-backed. Point out the exact defect, logical contradiction, or metric variance without sugarcoating."
    : "Constructive and empathetic. Begin with genuine recognition of intent before exploring areas of interpersonal or creative refinement.";

  const meetingPreference = isIntrovert
    ? "Lean & asynchronous. Agendas distributed 24 hours prior; concise 20-minute operational scrums over open-ended calls."
    : "Interactive & collaborative. Value face-to-face or video meetings where shared energy and cross-functional momentum can be fostered.";

  const decisionMakingStyle = isThinking
    ? "First-principles deductive logic. I evaluate trade-offs dispassionately and optimize for long-term systemic efficiency."
    : "Human-centric values alignment. I evaluate decisions against their impact on people, ethics, and communal trust.";

  const cognitiveDrainers = [
    isIntrovert
      ? "Endless back-to-back unscheduled meetings with zero solitary deep-work blocks."
      : "Prolonged isolation without collaborative sounding boards or verbal feedback.",
    isIntuitive
      ? "Repetitive manual data entry without conceptual autonomy or strategic context."
      : "Vague, speculative brainstorms that lack tangible deadlines or empirical data.",
    isJudging
      ? "Last-minute scope disruptions without logical justification or revised timelines."
      : "Rigid micro-management and inflexible procedures that stifle emergent creativity.",
  ];

  const cognitiveBoosters = [
    "Uninterrupted 2-3 hour deep focus blocks for flow state execution.",
    "Autonomous ownership of outcomes with clear definitions of success.",
    "Working alongside high-trust peers who respect intellectual honesty and deadlines.",
  ];

  const callsignLine = callsign
    ? `> **Callsign:** \`${callsign}\` │ **System ID:** WATQ Certified`
    : "";

  const markdownContent = `# User Manual: How to Work with Me
${callsignLine}
> **Archetype:** **${code}** — *${archetype.title}*  
> **Cognitive Stack:** \`${meta.cognitiveStack || "Autonomous"}\`  
> **Platform Standard:** [Watq — Personality Decoded](https://watq.mafrilearth.com)

---

## 🚀 Working Style & Philosophy
${workingStyle}

## 💬 Communication Protocol
* **Primary Channel:** ${communicationStyle}
* **Meeting Format:** ${meetingPreference}

## 🎯 How to Give Me Feedback
${howToGiveFeedback}

## ⚡ Cognitive Boosters (What Energizes Me)
${cognitiveBoosters.map((b) => `- ${b}`).join("\n")}

## 🔋 Cognitive Drainers (What Depletes My Energy)
${cognitiveDrainers.map((d) => `- ${d}`).join("\n")}

## 🧠 Decision-Making Logic
${decisionMakingStyle}

---
*Generated by [WATQ Sovereign Personality Platform](https://watq.mafrilearth.com)*
`;

  return {
    typeCode: code,
    archetypeTitle: archetype.title,
    callsign,
    workingStyle,
    communicationStyle,
    howToGiveFeedback,
    cognitiveDrainers,
    cognitiveBoosters,
    meetingPreference,
    decisionMakingStyle,
    markdownContent,
  };
}
